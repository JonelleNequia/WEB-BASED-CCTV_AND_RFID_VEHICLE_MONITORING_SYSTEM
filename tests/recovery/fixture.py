class Adapter(NativeRecovery):
    fixture = True

    def __init__(self, paths):
        super().__init__(paths); self.failure = None; self.config_calls = 0

    def admin(self):
        require('d5b-' in str(self.p['root']), 'Fixture adapter cannot target an installation')

    def machine(self): return 'synthetic-native-machine'

    def private(self, path):
        self.admin(); path = Path(path); path.mkdir(mode=0o700, parents=True, exist_ok=True); path.chmod(0o700)

    def permissions_for(self, role, path, verify=False):
        if self.failure == 'permissions': raise PermissionError('Synthetic permission refusal')
        path = Path(path)
        if path.exists():
            for child in [path] + (list(path.rglob('*')) if path.is_dir() else []):
                if not verify: child.chmod(0o700 if child.is_dir() else 0o600)
                else: require(child.stat().st_mode & 0o077 == 0, 'Unexpected fixture permissions: ' + role + '/' + child.name)

    def free(self, required):
        if self.failure == 'disk': raise OSError('Synthetic disk-full refusal')

    def snapshot(self): self.admin(); return {'owned_fixture': True}
    def quiesce(self, receipt): atomic(self.p['root'] / 'fixture-service.json', {'schema': 1, 'capture': False, 'access': False})
    def drain(self, seconds): pass
    def stop(self, receipt): self.quiesce(receipt)
    def verify(self, receipt):
        require(load(self.p['root'] / 'fixture-service.json') == {'schema': 1, 'capture': False, 'access': False}, 'Synthetic writer still running')

    def check(self):
        ident = identity(self.p['base'])
        with database(self.p['targets']['database']) as db:
            row = db.execute('SELECT installation,generation FROM delivery_installations').fetchone()
            require(row and all(row[k] == ident[k] for k in ('installation', 'generation')), 'Fixture DB identity mismatch')
            if (self.p['base'] / 'recovery-security.json').exists():
                marker = db.execute('SELECT epoch,active_set FROM recovery_state').fetchone(); ledger = load(self.p['base'] / 'recovery-security.json')
                require(marker['epoch'] == ledger['epoch'] and marker['active_set'] == ledger['active_set'], 'Fixture recovery epoch mismatch')

    def check_configuration(self): self.check(); self.config_calls += 1
    def start_access(self, receipt):
        if self.failure == 'access': raise OSError('Synthetic access failure')
        atomic(self.p['root'] / 'fixture-service.json', {'schema': 1, 'capture': False, 'access': True})
    def ready(self):
        if self.failure == 'ready': raise ValueError('Synthetic readiness failure')
    def reopen(self, receipt): atomic(self.p['root'] / 'fixture-service.json', {'schema': 1, 'capture': True, 'access': True})
    def prepare(self):
        if self.failure == 'prepare': raise ValueError('Synthetic generated-config failure')
        (self.p['targets']['storage'] / 'app/go2rtc').mkdir(parents=True, exist_ok=True)
        (self.p['targets']['storage'] / 'app/go2rtc/go2rtc.yaml').write_text('# regenerated by trusted fixture code\n')

    def crypto_check(self, payload):
        argument = {'database': str(payload / 'database/data'), 'environment': str(payload / 'environment/data'),
            'web': str(payload / 'tls'), 'tls_identity': str(payload / 'tls_identity/data'), 'public_root': str(payload / 'public_root/data')}
        if (payload / 'update_trust/trust.json').exists():
            argument['public_keys'] = {k: v['public_key'] for k, v in load(payload / 'update_trust/trust.json')['keys'].items()}
        result = subprocess.run([PHP, str(ROOT / 'deploy/lifecycle/recovery-check.php')], input=json.dumps(argument), text=True, capture_output=True, timeout=30)
        require(result.returncode == 0, 'Synthetic actual PHP crypto check failed: ' + result.stderr)
        return json.loads(result.stdout)


